"""Diagrams generated from the model itself, so they can't disagree with it."""

from .scheduler.eventrouter import EventRouter
from .scheduler.events import RULES, PriorityBoost
from .user import UserState

# Moves that aren't event reports: (from, to, label).
OTHER_MOVES = [
    (UserState.FREE_SLOT, UserState.READY, "startUser (ADD1)"),
    (UserState.READY, UserState.RUNNING, "dispatch (T:SE)"),
    (UserState.RUNNING, UserState.READY, "quantum end (T:CHSE0)"),
    (UserState.RUNNING, UserState.FREE_SLOT, "endUser (STEP70)"),
]


def stateMoves():
    """Every (from, to) pair a user can move along, with the reasons, from the transition
    table, the handlers' ``leadsTo`` marks, and ``OTHER_MOVES``. Staying put isn't a move."""
    moves = {}

    def add(fromState, toState, label):
        if fromState is not toState:
            labels = moves.setdefault((fromState, toState), [])
            if label not in labels:
                labels.append(label)

    for fromState, toState, label in OTHER_MOVES:
        add(fromState, toState, label)
    for rule in RULES:
        if isinstance(rule.action, UserState):
            targets = [(state, rule.action) for state in rule.states]
        elif isinstance(rule.action, PriorityBoost):
            targets = [(state, UserState.READY) for state in rule.states]
        else:
            mark = getattr(getattr(EventRouter, rule.action), "leadsTo", None)
            if mark is None:
                continue
            target, fromStates = mark
            targets = [(state, target) for state in rule.states
                       if fromStates is None or state in fromStates]
        for fromState, toState in targets:
            add(fromState, toState, rule.event.name)
    return moves


def renderStateDiagram():
    lines = ["# User states", "",
             "Generated by `python -m cpvmodel docs` from the transition table",
             "(`cpvmodel/events.py`) and the event router. Don't edit by hand.", "",
             "Each arrow is a move a user can make, labelled with the events (UPPER_CASE) or",
             "the other steps that cause it. Events that leave the state as it is, such as",
             "a break for a running user (it only sets a flag) or a kick-out (it only clears",
             "`inCore`), have no arrow.", "",
             "```mermaid", "stateDiagram-v2", "    [*] --> FREE_SLOT"]
    for (fromState, toState), labels in stateMoves().items():
        lines.append(f"    {fromState.name} --> {toState.name} : {', '.join(labels)}")
    lines += ["```", ""]
    return "\n".join(lines)
